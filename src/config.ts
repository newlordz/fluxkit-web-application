export interface Tool {
  id: string
  name: string
  description: string
  category: Category
  icon: LucideIcon
  available: boolean
  popular?: boolean
  integrationRequired?: boolean
  badgeColor?: ToolBadgeColor
  badgeIconType?: BadgeIconType
  formatBadge?: string
}

